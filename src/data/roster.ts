// Helper to assemble full character objects with promotion paths
function assembleCharacter(bp: CharacterBlueprint): Character {
  const baseRank = bp.baseRank;
  const promotionPath = [];

  // Generate promotion path for ranks lower than 5
  if (baseRank < 5) {
    const costs: Record<number, number> = { 2: 10, 3: 20, 4: 40, 5: 80 };
    for (let r = (baseRank + 1) as StarRank; r <= 5; r++) {
      const mult = 1 + (r - baseRank) * 0.35;
      promotionPath.push({
        toRank: r as StarRank,
        fragmentCost: costs[r] || 50,
        statMultipliers: {
          hp: Math.round(bp.hp * mult),
          jutsudmg: Number((bp.jutsudmg * (1 + (r - baseRank) * 0.25)).toFixed(2)),
          movespeed: Math.round(bp.movespeed * (1 + (r - baseRank) * 0.08)),
          collectradius: Math.round(bp.collectradius * (1 + (r - baseRank) * 0.15)),
          critchance: Number(Math.min(0.60, bp.critchance + (r - baseRank) * 0.05).toFixed(2)),
          critdmg: Number((bp.critdmg + (r - baseRank) * 0.15).toFixed(2)),
          defense: Math.round(bp.defense * (1 + (r - baseRank) * 0.40)),
          ryomultiplier: Number((bp.ryomultiplier * (1 + (r - baseRank) * 0.18)).toFixed(2)),
          chakraorbmultiplier: Number((bp.chakraorbmultiplier * (1 + (r - baseRank) * 0.22)).toFixed(2)),
        },
      });
    }
  }

  return {
    id: bp.id,
    nameJP: bp.nameJP,
    nameIT: bp.nameIT,
    form: bp.form,
    arc: bp.arc,
    baseRank: bp.baseRank,
    unlockedByDefault: bp.unlockedByDefault,
    element: bp.element,
    loreDescription: bp.loreDescription,
    jutsuSlot: {
      id: `${bp.id}_jutsu`,
      nameJP: bp.jutsuNameJP,
      nameIT: bp.jutsuNameIT,
      element: bp.element[0],
      category: bp.element.includes('SixPaths') ? 'SixPaths' : 'Ninjutsu',
      behavior: bp.jutsuBehavior,
      baseDmgCoeff: bp.jutsuBaseDmg,
      cooldownSec: bp.jutsuCooldown,
      cooldownPerLevel: 0.2,
      maxLevel: 8,
      isCombinationTrigger: true,
    },
    passiveAbility: {
      id: `${bp.id}_passive`,
      nameJP: bp.nameJP,
      nameIT: bp.passiveNameIT,
      category: bp.passiveCategory,
      element: bp.element[0],
      modifiers: bp.passiveModifiers,
      isCombinationComponent: false,
    },
    baseStats: {
      hp: bp.hp,
      jutsudmg: bp.jutsudmg,
      movespeed: bp.movespeed,
      collectradius: bp.collectradius,
      critchance: bp.critchance,
      critdmg: bp.critdmg,
      defense: bp.defense,
      ryomultiplier: bp.ryomultiplier,
      chakraorbmultiplier: bp.chakraorbmultiplier,
    },
    promotionPath,
    assets: {
      spriteSheet: `characters/${bp.id}.png`,
      portrait: `ui/portraits/${bp.id}.png`,
      jutsuVFX: `vfx/${bp.id}_vfx.png`,
      color: bp.color,
    },
  };
}

export const ROSTER: Character[] = BLUEPRINTS.map(assembleCharacter);

export function getCharacterById(id: string): Character | undefined {
  return ROSTER.find(c => c.id === id);
}
